#!/bin/bash
# Считает попадания одного прогона.
# Использование: score.sh <каталог случая> <файл с ответом модели>
# Печатает: найдено ожидалось ложных
# Код 2 — прогон сорвался (отказ провайдера, таймаут), считать нечего.
set -u

# Локаль задаётся здесь, а не снаружи: grep -i без UTF-8 не знает кириллического
# регистра, и «Ошибок нет» с заглавной перестаёт совпадать с «ошибок нет».
# Маркер снятия обвинения тогда теряется молча, а модель получает ложное
# срабатывание, которого не заслужила. Скрипт зовут и из run.sh, и из rescore.sh,
# и однажды позовут из cron, где LANG не выставлен.
export LC_ALL=C.UTF-8

DIR="${1:?каталог случая}"
ANSWER="${2:?файл с ответом модели}"

# Сорванный прогон отличать от нулевого результата: иначе отказ провайдера
# выглядит в таблице как плохая модель.
if grep -qE 'Internal Server Error|"code":5[0-9][0-9]|rate.?limit|Request timed out|terminated by signal' "$ANSWER"; then
  echo "- - -"
  exit 2
fi

# Модели ссылаются на строку кто во что горазд:
#   tokens.py:7 | **tokens.py, строки 7-9** | в файле `tokens.py` на строке 7 | tokens.py line 7
# Приводим к виду <файл>.py:<число>, иначе шаблон ловит одну форму из четырёх.
# Внутри [ ] только однобайтные символы: кириллица в скобочном классе распадается
# на байты вне UTF-8 локали и молча перестаёт работать.
NORM=$(mktemp)
trap 'rm -f "$NORM" "$NEG"' EXIT
NEG=""
LINE_WORD='строках|строки|строка|строке|строку|строк|lines|line'
PREP='на|в|at|on'
sed -E 's/\*+//g; s/`//g' "$ANSWER" \
  | sed -E "s/(\.py)[[:space:]]*[,;:-]*[[:space:]]*($PREP)?[[:space:]]*($LINE_WORD)?[[:space:]]*(No\.|#)?[[:space:]]*:?[[:space:]]*([0-9])/\1:\5/g" \
  > "$NORM"

: > "$ANSWER.missed"
found=0
expected=0
while IFS= read -r pat || [ -n "$pat" ]; do
  [ -z "${pat// /}" ] && continue
  expected=$((expected + 1))
  if grep -qiE -- "$pat" "$NORM"; then
    found=$((found + 1))
  else
    echo "$pat" >> "$ANSWER.missed"
  fi
done < "$DIR/expect.txt"

# Ложное срабатывание — это обвинение, а не упоминание. Модель, которая пишет
# «в bump_counter ошибки нет», символ проверила и очистила; засчитывать это как
# выдумку — значит наказывать за аккуратность. Поэтому упоминание считается
# только на строках без маркера снятия обвинения.
#
# Отрицательные формы заклеиваем заранее: «некорректно» содержит «корректно»,
# «неверно» содержит «верно», и без этой замены обвинение читалось бы как оправдание.
# Замена идёт по литералам, а не по классам [ ] — кириллица в скобочном классе
# распадается на байты вне UTF-8 локали и молча перестаёт работать.
NEG=$(mktemp)
# Окончания прилагательного и наречия, общие для всех основ ниже. Существительное
# на «-ость» сюда не входит намеренно: «корректность сомнительна» — это сомнение,
# а не оправдание, и читать его как снятие обвинения нельзя.
ADJ='(о|а|ы|ый|ая|ое|ые|ым|ой)'
STEM="корректн$ADJ|корректен|верн$ADJ|верен|правильн$ADJ|правилен|исправн$ADJ|исправен"

# Отрицание заклеиваем до проверки: «некорректно» содержит «корректно»,
# «неверен» содержит «верен». Без этой замены обвинение читалось бы как снятие.
sed -E "s/\\bне ?(вполне |совсем |всегда |до конца |полностью )?($STEM)\\b/ОБВИНЕНИЕ/g; s/\\bне в порядке\\b/ОБВИНЕНИЕ/g" "$NORM" > "$NEG"

# Маркеры снятия обвинения. Каждый закрыт границами слова с обеих сторон, иначе
# основа находится внутри чужого слова: «верен» лежит в «проверено», «корректн»
# в «корректность», «нет проблем» в «нет проблематично». Все три поймали
# ревьюеры 30.08.2026, и все три проверены прогоном, а не рассуждением.
CLEARED="\\bошибок нет\\b|\\bошибки нет\\b|\\bнет ошиб(ок|ки)\\b|\\bбез ошибок\\b|\\bне является ошибкой\\b|\\bне баг\\b|\\bне является багом\\b|\\bнет проблем\\b|\\bпроблем нет\\b|\\b($STEM)\\b|\\bв порядке\\b|no bug|no issue|no error|no problem|not a bug|not an error|is correct|are correct|works correctly|working correctly|is fine|are fine|looks correct|looks fine"

# ponytail: маркер снятия ищется на той же строке, что и символ. Строка вида
# «bump_counter сломан, foo корректен» будет прощена целиком. В формате этого
# стенда модели пишут одну находку на строку, поэтому случай редкий; если
# начнёт мешать — резать строку по запятой и проверять половины отдельно.
false_hits=0
if [ -f "$DIR/forbid.txt" ]; then
  while IFS= read -r pat || [ -n "$pat" ]; do
    [ -z "${pat// /}" ] && continue
    if grep -iE -- "$pat" "$NEG" | grep -qivE -- "$CLEARED"; then
      false_hits=$((false_hits + 1))
    fi
  done < "$DIR/forbid.txt"
fi

echo "$found $expected $false_hits"
