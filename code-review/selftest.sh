#!/bin/bash
# Проверка самого счётчика, без вызова моделей. Ловит поломку разбора expect/forbid
# и, главное, разные способы записи ссылки на строку.
set -u
ROOT="$(cd "$(dirname "$0")" && pwd)"
T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT
mkdir -p "$T/case"
printf 'issue_stamp|created_at or time|tokens\.py:[0-9]\n' > "$T/case/expect.txt"
printf 'clamp_ttl\n' > "$T/case/forbid.txt"

fail=0
check() {
  local name="$1" want="$2" got="$3"
  if [ "$want" = "$got" ]; then
    echo "ок    $name"
  else
    echo "СБОЙ  $name: ожидалось [$want], получено [$got]"
    fail=1
  fi
}

run() { "$ROOT/score.sh" "$T/case" "$1"; }

printf 'ISSUE_STAMP подставляет текущее время\n'   > "$T/a.txt"
check "по имени функции"          "1 1 0" "$(run "$T/a.txt")"

printf 'tokens.py:7 — значение подменяется\n'      > "$T/b.txt"
check "файл:строка через двоеточие" "1 1 0" "$(run "$T/b.txt")"

printf '**tokens.py, строки 7-9**: значение подменяется\n' > "$T/c.txt"
check "запятая и слово строки"      "1 1 0" "$(run "$T/c.txt")"

printf 'в файле `tokens.py` на строке 7 неверно\n' > "$T/d.txt"
check "предлог и обратные кавычки"  "1 1 0" "$(run "$T/d.txt")"

printf 'tokens.py line 7 is wrong\n'               > "$T/e.txt"
check "английская форма"            "1 1 0" "$(run "$T/e.txt")"

printf 'clamp_ttl не имеет верхней границы\n'      > "$T/f.txt"
check "ложное срабатывание"         "0 1 1" "$(run "$T/f.txt")"

# Ниже — про разницу между обвинением и упоминанием. Счётчик когда-то считал
# ложным срабатыванием любое упоминание запрещённого символа, включая фразу
# «здесь ошибки нет», то есть наказывал модель за то, что она проговорила
# проверенное. Поймано 30.08.2026 на двух ответах glm-5.3-flash.

printf 'В clamp_ttl ошибки нет\n'                  > "$T/f1.txt"
check "снятие: ошибки нет"          "0 1 0" "$(run "$T/f1.txt")"

printf 'Остальное (clamp_ttl, is_alive) корректно.\n' > "$T/f2.txt"
check "снятие: перечисление корректных" "0 1 0" "$(run "$T/f2.txt")"

printf 'clamp_ttl works correctly, no bug there\n' > "$T/f3.txt"
check "снятие по-английски"         "0 1 0" "$(run "$T/f3.txt")"

printf 'clamp_ttl отрабатывает некорректно\n'      > "$T/f4.txt"
check "ловушка: некорректно это обвинение" "0 1 1" "$(run "$T/f4.txt")"

printf 'clamp_ttl считает неверно\n'               > "$T/f5.txt"
check "ловушка: неверно это обвинение" "0 1 1" "$(run "$T/f5.txt")"

printf 'clamp_ttl не ограничивает сверху\nis_alive корректно\n' > "$T/f6.txt"
check "снятие соседа не спасает обвиняемого" "0 1 1" "$(run "$T/f6.txt")"

printf 'tokens.py:7 issue_stamp подменяет время\nВ clamp_ttl ошибок нет\n' > "$T/f7.txt"
check "находка засчитана, снятие не наказано" "1 1 0" "$(run "$T/f7.txt")"

printf 'clamp_ttl отрабатывает не в порядке\n'      > "$T/f8.txt"
check "ловушка: не в порядке это обвинение" "0 1 1" "$(run "$T/f8.txt")"

# Локаль. grep -i без UTF-8 не знает кириллического регистра, поэтому «Ошибок нет»
# с заглавной перестаёт быть маркером снятия и превращается в ложное срабатывание.
# Скрипт обязан выставлять локаль сам: снаружи её однажды не будет (cron).
printf 'В clamp_ttl Ошибок нет\n'                  > "$T/f9.txt"
check "снятие с заглавной буквы"    "0 1 0" "$(run "$T/f9.txt")"

# Беглая гласная. Краткая форма прилагательного теряет букву: «корректен», а не
# «корректны». Первая версия списка ловила только «корректн» и «верн», поэтому
# «clamp_ttl корректен» засчитывалось как выдумка. Поймано ревьюером deepseek-chat
# 30.08.2026 и подтверждено прогоном, а не рассуждением.

printf 'clamp_ttl корректен\n'                     > "$T/g1.txt"
check "снятие краткой формой: корректен" "0 1 0" "$(run "$T/g1.txt")"

printf 'clamp_ttl верен\n'                         > "$T/g2.txt"
check "снятие краткой формой: верен"     "0 1 0" "$(run "$T/g2.txt")"

printf 'clamp_ttl неверен\n'                       > "$T/g3.txt"
check "ловушка: неверен это обвинение"   "0 1 1" "$(run "$T/g3.txt")"

printf 'clamp_ttl некорректен\n'                   > "$T/g4.txt"
check "ловушка: некорректен это обвинение" "0 1 1" "$(run "$T/g4.txt")"

# Граница слова: «верен» лежит внутри «проверено», и без \\b обвинение
# «проверено, что символ падает» читалось бы как снятие.
printf 'Проверено: clamp_ttl падает на нуле\n'     > "$T/g5.txt"
check "проверено это не снятие"          "0 1 1" "$(run "$T/g5.txt")"

# Основа внутри чужого слова. Все три случая назвали ревьюеры 30.08.2026,
# все три воспроизведены прогоном до правки.

printf 'clamp_ttl: корректность сомнительна\n'     > "$T/h1.txt"
check "корректность это не снятие"       "0 1 1" "$(run "$T/h1.txt")"

printf 'clamp_ttl: верность вычисления под вопросом\n' > "$T/h2.txt"
check "верность это не снятие"           "0 1 1" "$(run "$T/h2.txt")"

printf 'clamp_ttl: нет проблематично округляет\n'  > "$T/h3.txt"
check "проблематично это не снятие"      "0 1 1" "$(run "$T/h3.txt")"

printf 'clamp_ttl работает правильно\n'            > "$T/h4.txt"
check "снятие: работает правильно"       "0 1 0" "$(run "$T/h4.txt")"

printf 'clamp_ttl работает неправильно\n'          > "$T/h5.txt"
check "ловушка: неправильно это обвинение" "0 1 1" "$(run "$T/h5.txt")"

# Смягчённое обвинение. «не вполне корректно» — это претензия, но «не» стоит не
# вплотную к основе, и без вставки усилителей строка читалась бы как снятие.
# Нашёл ревьюер kimi-k2.7-code 30.08.2026, воспроизведено до правки.

printf 'clamp_ttl работает не вполне корректно\n'  > "$T/h6.txt"
check "ловушка: не вполне корректно"     "0 1 1" "$(run "$T/h6.txt")"

printf 'clamp_ttl считает не совсем верно\n'       > "$T/h7.txt"
check "ловушка: не совсем верно"         "0 1 1" "$(run "$T/h7.txt")"

printf 'clamp_ttl отрабатывает не всегда правильно\n' > "$T/h8.txt"
check "ловушка: не всегда правильно"     "0 1 1" "$(run "$T/h8.txt")"
check "то же под LC_ALL=C"          "0 1 0" "$(LC_ALL=C run "$T/f9.txt")"
check "то же без LANG"              "0 1 0" "$(env -u LANG -u LC_ALL "$ROOT/score.sh" "$T/case" "$T/f9.txt")"

: > "$T/g.txt"
check "пустой ответ"                "0 1 0" "$(run "$T/g.txt")"

printf 'Error: Internal Server Error: {"error":{"code":500}}\n' > "$T/h.txt"
out=$(run "$T/h.txt"); rc=$?
check "сорванный прогон отличён от нуля" "- - - 2" "$out $rc"

check "промах записан в .missed" "issue_stamp|created_at or time|tokens\.py:[0-9]" "$(cat "$T/f.txt.missed")"

exit $fail
