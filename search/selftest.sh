#!/usr/bin/env bash
# Проверяет сам счётчик на подложных ответах. На стенде моделей счётчик
# занижал четыре раза подряд, и каждый раз это выглядело как результат.
set -u
cd "$(dirname "$0")"
T=$(mktemp -d); mkdir -p "$T/answers"
w(){ printf '%s\n' "$2" > "$T/answers/$1.md"; }
pad="Дополнительный текст, чтобы файл не считался сорванным прогоном. Ещё немного слов."

w "x-r1-q1" "Последняя версия — Playwright v1.62.1 от 30 июля 2026. $pad"
w "x-r2-q1" "Актуальная версия Playwright 1.61.0. $pad"
w "x-r1-q2" "У репозитория примерно 3044 звезды. $pad"
w "x-r2-q2" "Около 3.0k звёзд на GitHub. $pad"
w "x-r3-q2" "У репозитория 2500 звёзд. $pad"
w "x-r1-q5" "Модели sonar-reasoning без суффикса -pro не существует. $pad"
w "x-r2-q5" "sonar-reasoning стоит \$1 за миллион входных токенов. $pad"
w "x-r1-q7" "Нужен флаг --force вместе с --incremental. $pad"
w "x-r2-q7" "Используйте --rerun-all. $pad"
w "x-r1-q6" "Эндпоинт /api/v1/credits возвращает total_credits и total_usage. $pad"
w "x-r1-q3" "Генерация тестов теперь работает без привязки к таск-трекеру. $pad"
w "x-r1-q4" "Подключаются ГигаЧат, YandexGPT и любые OpenAI-совместимые сервисы. $pad"
w "x-r1-q8" "За один прогон можно получить до 30 тест-кейсов. $pad"
w "x-r9-q1" "нет"

out=$(./score.sh questions.tsv "$T/answers")
fail=0
chk(){ # описание, ожидаемая строка
  if printf '%s\n' "$out" | grep -qF "$2"; then printf 'ok   %s\n' "$1"
  else printf 'FAIL %s (нет строки: %s)\n' "$1" "$2"; fail=1; fi
}
chk "точная версия засчитана"          "x,1,q1,свежесть,да,-,"
chk "чужая версия не засчитана"        "x,2,q1,свежесть,нет,-,"
chk "число звёзд засчитано"            "x,1,q2,свежесть,да,-,"
chk "форма 3.0k засчитана"             "x,2,q2,свежесть,да,-,"
chk "далёкое число не засчитано"       "x,3,q2,свежесть,нет,-,"
chk "ловушка: отказ засчитан"          "x,1,q5,ловушка,да,нет,"
chk "ловушка: выдумка поймана"         "x,2,q5,ловушка,нет,да,"
chk "флаг --force засчитан"            "x,1,q7,деталь в доках,да,-,"
chk "выдуманный флаг не засчитан"      "x,2,q7,деталь в доках,нет,-,"
chk "поле total_credits засчитано"     "x,1,q6,деталь в доках,да,-,"
chk "русский ответ q3 засчитан"        "x,1,q3,русский источник,да,-,"
chk "русский ответ q4 засчитан"        "x,1,q4,русский источник,да,-,"
chk "русский ответ q8 засчитан"        "x,1,q8,русский источник,да,-,"
chk "пустой ответ помечен сорванным"   "x,9,q1,свежесть,сорвано,-,"
rm -rf "$T"
[ $fail -eq 0 ] && echo "--- счётчик исправен" || echo "--- счётчик врёт, чинить до прогона"
exit $fail
